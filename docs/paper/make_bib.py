"""Build docs/paper/refs.bib from the verified DOIs / arXiv IDs in docs/related_work.md (never typed by hand).

    python docs/paper/make_bib.py
"""

import re
import sys
import time
import xml.etree.ElementTree as ET
from pathlib import Path

import httpx

HERE = Path(__file__).resolve().parent
RW = HERE.parent / "related_work.md"
ATOM = "{http://www.w3.org/2005/Atom}"


def key_of(first_author: str, year: str, word: str) -> str:
    return re.sub(r"[^a-z0-9]", "", (first_author + year + word).lower())


def clean(bib: str) -> str:
    """HTML entities/tags from Crossref -> LaTeX; duplicate keys get a/b/c suffixes."""
    bib = bib.replace("&amp;", r"\&").replace("&lt;sub&gt;", "<sub>").replace("&lt;/sub&gt;", "</sub>")
    bib = re.sub(r"\s*<sub>\s*([^<]+?)\s*</sub>(\s*)", lambda m: f"$_{{{m.group(1)}}}$" + (" " if m.group(2) else ""), bib)
    bib = re.sub(r"[ \t]*\n[ \t]+(?=[^@\s])", " ", bib)  # Crossref wraps some titles over lines
    seen: dict[str, int] = {}

    def rekey(m):
        k = m.group(2)
        seen[k] = seen.get(k, 0) + 1
        return f"@{m.group(1)}{{{k}{'' if seen[k] == 1 else chr(96 + seen[k])},"

    return re.sub(r"@(\w+)\{([^,]+),", rekey, bib)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    text = RW.read_text(encoding="utf-8")
    dois = sorted(set(re.findall(r"https://doi\.org/(10\.[^\s)]+)", text)))
    arx = sorted(set(re.findall(r"arxiv\.org/abs/(\d{4}\.\d{4,5})", text)))
    c = httpx.Client(timeout=60, follow_redirects=True, headers={"User-Agent": "AeroFusion-bib (mailto:shashankkaranamr@gmail.com)"})
    out = [f"% generated by docs/paper/make_bib.py from docs/related_work.md ({len(dois)} DOIs, {len(arx)} arXiv)\n"]
    for d in dois:
        r = c.get(f"https://doi.org/{d}", headers={"Accept": "application/x-bibtex"})
        if r.status_code == 200 and r.text.strip().startswith("@"):
            out.append(r.text.strip() + "\n")
        else:
            out.append(f"% FAILED to fetch BibTeX for doi:{d} (HTTP {r.status_code})\n")
        time.sleep(0.3)
    for a in arx:
        e = ET.fromstring(c.get("https://export.arxiv.org/api/query", params={"id_list": a}).text).find(f"{ATOM}entry")
        title = " ".join(e.find(f"{ATOM}title").text.split())
        authors = " and ".join(x.find(f"{ATOM}name").text for x in e.findall(f"{ATOM}author"))
        year = e.find(f"{ATOM}published").text[:4]
        k = key_of(authors.split(" and ")[0].split()[-1], year, title.split()[0])
        out.append(f"@misc{{{k},\n  title = {{{title}}},\n  author = {{{authors}}},\n  year = {{{year}}},\n  eprint = {{{a}}},\n  archivePrefix = {{arXiv}},\n  url = {{https://arxiv.org/abs/{a}}}\n}}\n")
        time.sleep(3)
    (HERE / "refs.bib").write_text(clean("\n".join(out)), encoding="utf-8")
    print(f"wrote refs.bib: {len(dois)} DOIs, {len(arx)} arXiv; failures: {sum('FAILED' in o for o in out)}")


if __name__ == "__main__":
    main()
