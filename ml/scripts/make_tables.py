"""Generate paper/report tables from run artifacts only (PROGRESS §0 rule 1). Never type a number into a table by hand.

    python ml/scripts/make_tables.py

Reads ml/runs/*/metrics.json (latest run per model and split) and writes, per split, docs/paper/tables/<split>_baselines.tex
(LaTeX rows, each ending with a `% run_id: ...` comment, which tests/test_no_illustrative_metrics.py checks) and a
markdown copy for the report and README. Test-split tables are only written once final_eval.py has produced them.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ML = Path(__file__).resolve().parents[1]
REPO = ML.parent
OUT = REPO / "docs" / "paper" / "tables"
LEADS = ["1", "24", "48"]


def latest_runs() -> dict[tuple[str, str, str], dict]:
    best: dict[tuple[str, str, str], dict] = {}
    for f in sorted((ML / "runs").glob("*/metrics.json")):
        m = json.loads(f.read_text(encoding="utf-8"))
        if m.get("status") != "measured":
            continue
        best[(m["split"], m["setting"], m["model"])] = m  # sorted by run_id (date first) -> last wins
    return best


def fmt(v, nd=1):
    return "--" if v is None else f"{v:.{nd}f}"


def table(split: str, runs: list[dict]) -> tuple[str, str]:
    tex = [f"% generated by ml/scripts/make_tables.py from ml/runs/*/metrics.json; split={split}. Do not edit.",
           r"\begin{tabular}{l" + "rrr" * len(LEADS) + "}", r"\toprule",
           "Model & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{+{L} h}}" for L in LEADS) + r" \\",
           " & " + " & ".join(["RMSE & MAE & Skill"] * len(LEADS)) + r" \\", r"\midrule"]
    md = [f"| Model ({split}) | " + " | ".join(f"RMSE +{L}h | MAE +{L}h | skill vs pers. +{L}h" for L in LEADS) + " | run_id |",
          "|---|" + "---|" * (3 * len(LEADS)) + "---|"]
    for m in sorted(runs, key=lambda r: r["model"]):
        cells = []
        for L in LEADS:
            s = m["leads"][L]["station"]
            cells += [fmt(s["rmse"]), fmt(s["mae"]), fmt(s.get("skill_vs_persistence"), 3)]
        name = m["model"].replace("_", r"\_")
        tex.append(f"{name} & " + " & ".join(cells) + rf" \\ % run_id: {m['run_id']}")
        md.append(f"| {m['model']} | " + " | ".join(cells) + f" | `{m['run_id']}` |")
    tex += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(tex), "\n".join(md) + "\n"


def main() -> None:
    runs = latest_runs()
    OUT.mkdir(parents=True, exist_ok=True)
    for split in sorted({k[0] for k in runs}):
        if split == "test" and "--final" not in sys.argv:
            continue
        for setting in sorted({k[1] for k in runs if k[0] == split}):
            sel = [m for k, m in runs.items() if k[0] == split and k[1] == setting]
            tex, md = table(split, sel)
            stem = f"{split}_{setting.replace('-', '').lower()}_station"
            (OUT / f"{stem}.tex").write_text(tex, encoding="utf-8")
            (OUT / f"{stem}.md").write_text(md, encoding="utf-8")
            print(f"wrote {stem}.tex/.md ({len(sel)} models)")


if __name__ == "__main__":
    main()
