"""Generate ml/data/DATA_CARD.md: QC counts per rule and per-station coverage (PROGRESS §3.7).

    python ml/scripts/make_data_card.py

Covers train + val only (2017-12-01 .. 2022-12-31 UTC). The frozen test split is QC'd by the same rules inside the
P1.10 build, but its statistics are not computed or reported here.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import pandas as pd
import yaml

ML = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ML))
from aerofusion_ml.data import cpcb, qc  # noqa: E402

DATA = ML / "data"
T0, T1 = "2017-12-01 00:00", "2022-12-31 23:00"


def main() -> None:
    splits = yaml.safe_load((ML / "configs" / "splits_v1.yaml").read_text(encoding="utf-8"))["splits"]
    if pd.Timestamp(T1) >= pd.Timestamp(splits["test"]["start"]):
        raise SystemExit("data card window overlaps the frozen test split")
    panel = pd.read_csv(DATA / "stations_v1.csv")
    ids = panel["station_id"].tolist()
    city_of = dict(zip(panel["station_id"], panel["city"]))
    long = cpcb.load_long(ids, "2017-12", "2022-12")

    rows, frames, dups = [], {}, {}
    for p in cpcb.PARAMS.values():
        w, dups[p] = cpcb.wide(long, p, ids, T0, T1)
        clean, stats = qc.run_qc(w, p, city_of)
        frames[p] = clean
        rows.append(stats)
    counts = pd.DataFrame(rows).set_index("pollutant")
    for c in ["removed_bounds_sentinel", "removed_flatline", "removed_spike"]:
        counts[c.replace("removed_", "%")] = (100 * counts[c] / counts["observed"]).round(2)
    counts["duplicates_averaged"] = pd.Series(dups)
    ratio = qc.pm_ratio_flags(frames["pm25"], frames["pm10"])
    n_ratio = int(ratio.sum().sum())
    n_pair = int((frames["pm25"].notna() & frames["pm10"].reindex_like(frames["pm25"]).notna()).sum().sum())

    def coverage(df: pd.DataFrame, a: str, b: str) -> pd.Series:
        s = df.loc[pd.Timestamp(a, tz="UTC"):pd.Timestamp(b + " 23:00", tz="UTC")]
        return (100 * s.notna().mean()).round(1)

    cov = pd.DataFrame({
        "pm25_train_%": coverage(frames["pm25"], splits["train"]["start"], splits["train"]["end"]),
        "pm25_val_%": coverage(frames["pm25"], splits["val"]["start"], splits["val"]["end"]),
        **{f"{p}_train_%": coverage(frames[p], splits["train"]["start"], splits["train"]["end"]) for p in ["pm10", "no2", "co", "o3"]},
    })
    cov.insert(0, "city", cov.index.map(city_of))
    cov.index.name = "station_id"
    cov.sort_values(["city", "pm25_train_%"]).to_csv(DATA / "coverage_v1_trainval.csv")
    by_city = cov.groupby("city")[["pm25_train_%", "pm25_val_%"]].median().round(1)
    by_city.insert(0, "stations", cov.groupby("city").size())

    md = [
        "# DATA_CARD (generated by `ml/scripts/make_data_card.py`; do not edit by hand)",
        "",
        f"Generated {date.today().isoformat()}. Source: XKDR bulk export of CPCB CAAQM (+ US Embassy) hourly data, "
        f"CC BY 4.0. Panel: `stations_v1.csv` ({len(ids)} stations, {panel['city'].nunique()} cities). "
        f"Window: {T0} → {T1} UTC (**train + val only**; test-split statistics are not computed here).",
        "",
        "## QC removals per rule (§3.7, `aerofusion_ml/data/qc.py`)",
        "Counts are station-hours. A spike flagged at ≥ 2 stations of the same city in the same hour is kept as a real event.",
        "",
        counts[["observed", "removed_bounds_sentinel", "%bounds_sentinel", "removed_flatline", "%flatline", "removed_spike", "%spike", "kept_city_event", "remaining", "duplicates_averaged"]].to_markdown(),
        "",
        f"PM2.5 > 1.05 × PM10 (flag only, kept): {n_ratio:,} of {n_pair:,} hours with both "
        f"({100 * n_ratio / max(n_pair, 1):.2f} %).",
        "",
        "## PM2.5 coverage after QC (% of hours with a value), median per city",
        "",
        by_city.to_markdown(),
        "",
        "Per-station coverage for all pollutants: `coverage_v1_trainval.csv`.",
        "Targets are never filled. Input gaps ≤ 3 h are interpolated at build time (P1.10), longer gaps stay NaN + mask.",
        "",
    ]
    (DATA / "DATA_CARD.md").write_text("\n".join(md), encoding="utf-8")
    print(counts.to_string())
    print(f"ratio flags {n_ratio}/{n_pair}")
    print(by_city.describe().round(1).to_string())


if __name__ == "__main__":
    main()
