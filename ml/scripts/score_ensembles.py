"""Score the 5-seed ensembles pre-registered in ml/MODEL_FREEZE.json ("reported_ensembles", "serving_model").

    python ml/scripts/score_ensembles.py [--split test]

Reads only the per-seed predictions that final_eval.py already wrote (preds_<split>.parquet); it does not read the frozen
inputs again. The ensemble forecast is the mean of the seeds' µg/m³ forecasts. Writes
  docs/paper/tables/ensembles_<split>.{md,json}
  backend/app/data/model_metrics.json  (serving model; city and station blocks with skill vs persistence and CAMS-BC,
                                        skill = 1 - RMSE / RMSE of the baseline from its own metrics_<split>.json)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

ML = Path(__file__).resolve().parents[1]
REPO = ML.parent
sys.path.insert(0, str(ML))
from aerofusion_ml import evaluate as ev  # noqa: E402

KEY = ["t0", "lead", "node_id"]


def ens_preds(run_ids: list[str], split: str) -> pd.DataFrame:
    dfs = [pd.read_parquet(ML / "runs" / r / f"preds_{split}.parquet") for r in run_ids]
    base = dfs[0][KEY + ["obs"]]
    p = pd.concat([d.set_index(KEY)["pred"].rename(i) for i, d in enumerate(dfs)], axis=1).mean(axis=1).rename("pred")
    return base.join(p, on=KEY)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test")
    a = ap.parse_args()
    fz = json.loads((ML / "MODEL_FREEZE.json").read_text(encoding="utf-8"))
    ds = xr.open_zarr(ML / "data/processed/dataset_v1.zarr")
    city_of = dict(zip([str(v) for v in ds.node.values], [str(v) for v in ds.node_city_slug.values]))
    leads = ev.load_cfg()["leads_report"]
    rows, out = [], {}
    for m in fz["reported_ensembles"]["models"]:
        rids = [r for r in fz["run_ids"] if f"-{m}-s" in r]
        df = ens_preds(rids, a.split)
        met = ev.evaluate(df, split=a.split, model=m + "_ens5", setting="", run_id="+".join(rids), city_of=city_of, allow_test=True)
        out[m] = {L: met["leads"][str(L)]["station"] for L in leads}
        rows.append(f"| {m} | " + " | ".join(f"{met['leads'][str(L)]['station']['rmse']:.1f}" for L in leads) + " |")
        print(m, [round(met["leads"][str(L)]["station"]["rmse"], 2) for L in leads], flush=True)
    tabs = REPO / "docs" / "paper" / "tables"
    (tabs / f"ensembles_{a.split}.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    md = [f"5-seed ensemble (mean forecast) station RMSE, split {a.split}, commit {fz['git_commit']}; pre-registered in MODEL_FREEZE.json. "
          "Generated by ml/scripts/score_ensembles.py; do not edit.", "", "| Model | " + " | ".join(f"RMSE +{L} h" for L in leads) + " |",
          "|---" * (len(leads) + 1) + "|"] + rows
    (tabs / f"ensembles_{a.split}.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    # serving model with skills against persistence and CAMS-BC on the same rows
    sv = fz["serving_model"]
    df = ens_preds(sv["run_ids"], a.split)
    met = ev.evaluate(df, split=a.split, model="abl_no_gating_ens5", setting="S-A", run_id=", ".join(sv["run_ids"]), city_of=city_of, allow_test=True)
    # skill against persistence and CAMS-BC from their final_eval metrics (final_eval saved their scores, not their forecasts)
    for name, ref in [("persistence", fz["baselines"]["persistence"]), ("cams", fz["baselines"]["cams_bc"])]:
        rm = json.loads((ML / "runs" / ref / f"metrics_{a.split}.json").read_text(encoding="utf-8"))
        for L, blk in met["leads"].items():
            for lvl in ("city", "station"):
                blk[lvl][f"skill_vs_{name}"] = ev.skill(blk[lvl]["rmse"], rm["leads"][L][lvl]["rmse"])
    live = ML / "data/raw/logs/post/extra/live_mode_val.json"
    serve = {"status": "measured", "run_id": ", ".join(sv["run_ids"]), "split": met["split"], "setting": "S-A",
             "model": "MW-AeroFusion-Net without gating (mean of 5 seeds)", "git_commit": fz["git_commit"],
             "n_issue_times": met["n_issue_times"], "n_stations": met["n_stations"],
             "leads": {k: {"city": v["city"], "station": v["station"], "episodes": v["episodes"], "aqi": v["aqi"]} for k, v in met["leads"].items()}}
    if live.exists():
        lv = json.loads(live.read_text(encoding="utf-8"))
        serve["live_replay"] = {"note": "validation 2022 replayed with no station pollutant inputs and no dust AOD (the live site's inputs)",
                                "rmse": lv["rmse"]["live_none"]}
    (REPO / "backend" / "app" / "data" / "model_metrics.json").write_text(json.dumps(serve, indent=1), encoding="utf-8")
    print("serving model", {k: round(v["city"]["rmse"], 1) for k, v in serve["leads"].items()},
          {k: (round(v["city"].get("skill_vs_persistence") or 0, 3), round(v["city"].get("skill_vs_cams") or 0, 3)) for k, v in serve["leads"].items()})


if __name__ == "__main__":
    main()
